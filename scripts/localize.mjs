import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const source = JSON.parse(await readFile(new URL('localization/translations.json', root), 'utf8'));
const { languages, rows } = source;
if (languages.some(item => ['he', 'iw'].includes(item.code)) || new Set(rows.map(row => row[0])).size !== rows.length) throw new Error('Invalid locales or duplicate messages');
const parameters = text => [...text.matchAll(/\{([a-z]+)\}/g)].map(match => match[1]).sort().join(',');
for (const row of rows) if (row.length !== languages.length || row.some(text => typeof text !== 'string' || !text.trim() || parameters(text) !== parameters(row[0]))) throw new Error('Incomplete translation or parameter mismatch: ' + row[0]);
const dictionaries = {};
const outputs = new Map();
for (const [browser, name] of Object.entries({ chrome: 'Google Chrome', edge: 'Microsoft Edge', firefox: 'Mozilla Firefox' })) {
  for (const suffix of ['', '.fa']) {
    const base = await readFile(new URL(`store/PRIVACY${suffix}.md`, root), 'utf8');
    const limitedUse = browser === 'chrome' ? (suffix ? '\nاستفادهٔ این افزونه از اطلاعات با سیاست دادهٔ کاربر Chrome Web Store، از جمله الزامات Limited Use، مطابقت دارد.\n' : '\nThe extension’s handling of information complies with the Chrome Web Store User Data Policy, including its Limited Use requirements.\n') : '';
    outputs.set(`store/${browser}/PRIVACY${suffix}.md`, base.replace(/^# .*$/m, suffix ? `# حریم خصوصی AdBlocker — ${name}` : `# AdBlocker privacy policy — ${name}`) + limitedUse);
  }
}
for (const [index, language] of languages.entries()) {
  dictionaries[language.code] = Object.fromEntries(rows.slice(0, -2).map(row => [row[0], row[index]]));
  const messages = {};
  messages.extensionName = { message: 'AdBlocker — Browse without ads' };
  messages.extensionDescription = { message: rows.at(-2)[index] };
  if (messages.extensionDescription.message.length > 132) throw new Error('Manifest description too long: ' + language.code);
  outputs.set(`extension/_locales/${language.code.replace('-', '_')}/messages.json`, JSON.stringify(messages, null, 2) + '\n');
  for (const browser of ['chrome', 'edge', 'firefox']) {
    outputs.set(`store/${browser}/listings/${language.code}.md`, `# AdBlocker\n\n${messages.extensionDescription.message}\n\n${rows.at(-1)[index]}\n\nhttps://github.com/salehghotbani/AdBlocker/blob/main/store/${browser}/PRIVACY.md\n`);
  }
}
outputs.set('extension/locale-data.js', '// Generated by scripts/localize.mjs from localization/translations.json.\n' +
  'globalThis.AdBlockLocales = ' + JSON.stringify({ languages, dictionaries }, null, 2) + ';\n');
for (const [file, content] of outputs) {
  const url = new URL(file, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error('Stale generated localization: ' + file);
  } else { await mkdir(new URL('./', url), { recursive: true }); await writeFile(url, content); }
}
console.log(`PASS: ${languages.length} complete languages, ${rows.length} messages, localized store descriptions; English default`);
